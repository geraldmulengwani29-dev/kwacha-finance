/**
 * Escapes HTML characters to prevent XSS.
 * Should be used when manually constructing HTML strings that include user-controlled data.
 */
export const escapeHTML = (str) => {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
};
